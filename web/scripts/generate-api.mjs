import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const temporary = mkdtempSync(join(tmpdir(), "loop-reviewer-openapi-"));
try {
	const schema = join(temporary, "openapi.json");
	writeFileSync(
		schema,
		execFileSync("uv", [
			"--directory",
			"..",
			"run",
			"--locked",
			"python",
			"-m",
			"loop_reviewer.local_http.export_schema",
		]),
	);
	const declaration =
		"/* Generated by pnpm api:generate. */\n\n" +
		astToString(await openapiTS(pathToFileURL(schema)));
	const output = new URL("../src/api/schema.d.ts", import.meta.url);
	if (process.argv.includes("--check")) {
		if (readFileSync(output, "utf8") !== declaration) {
			throw new Error(
				"API declaration is stale. Run pnpm --dir web api:generate.",
			);
		}
	} else {
		writeFileSync(output, declaration);
	}
} finally {
	rmSync(temporary, { recursive: true, force: true });
}
